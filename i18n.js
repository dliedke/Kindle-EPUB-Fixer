  let currentLanguage = detectBrowserLanguage();

  function detectBrowserLanguage() {
    const languages = Array.isArray(navigator.languages) && navigator.languages.length
      ? navigator.languages
      : [navigator.language || "en"];
    const preferredLanguage = languages[0] || "en";
    return /^pt(?:-|$)/i.test(preferredLanguage) ? "pt" : "en";
  }

  function interpolate(template, variables = {}) {
    return String(template).replace(/\{\{\s*([\w.]+)\s*\}\}/g, (match, key) => {
      return Object.prototype.hasOwnProperty.call(variables, key) ? String(variables[key]) : match;
    });
  }

  function t(key, variables = {}) {
    const dictionary = translations[currentLanguage] || translations.en;
    const fallback = translations.en[key] || key;
    return interpolate(dictionary[key] || fallback, variables);
  }

  function has(key) {
    return Boolean((translations[currentLanguage] || translations.en)[key] || translations.en[key]);
  }

  function applyTranslations(root = document) {
    root.querySelectorAll("[data-i18n]").forEach((element) => {
      element.textContent = t(element.dataset.i18n);
    });
    root.querySelectorAll("[data-i18n-title]").forEach((element) => {
      element.title = t(element.dataset.i18nTitle);
    });
    root.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
      element.setAttribute("aria-label", t(element.dataset.i18nAriaLabel));
    });
    document.documentElement.lang = currentLanguage === "pt" ? "pt-BR" : "en";
    document.title = t("document.title");
  }

  function setLanguage(language) {
    currentLanguage = language === "pt" ? "pt" : "en";
    applyTranslations();
    window.dispatchEvent(new CustomEvent("epubfixer:languagechange", { detail: { language: currentLanguage } }));
  }

  function initialize() {
    applyTranslations();
    return currentLanguage;
  }

  window.EpubFixerI18n = Object.freeze({
    initialize,
    setLanguage,
    getLanguage: () => currentLanguage,
    detectBrowserLanguage,
    applyTranslations,
    t,
    has
  });
